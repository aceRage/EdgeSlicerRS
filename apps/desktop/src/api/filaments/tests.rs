//! The filament list through the session: adding, removing, deleting and
//! merging, colours and "Apply All", each one step of the history, the
//! project unsaved, its slices let go, saved and opened again.

use std::{path::Path, sync::Arc};

use serde_json::{Value, json};

use super::super::Session;

const THREE_PLATES: &str = "tests/mcbrim_test.3mf";
const BARE: &str = "resources/handy_models/OrcaToleranceTest.stl";
const MACHINE: &str = "Snapmaker U1 (0.4 nozzle)";

fn reference(path: &str) -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../reference/EdgeSlicer")
        .join(path)
}

fn ask(session: &Arc<Session>, name: &str, args: Value) -> Value {
    session
        .call(name, &args)
        .unwrap_or_else(|error| panic!("{name} {args}: {error}"))
}

fn refused(session: &Arc<Session>, name: &str, args: Value) -> String {
    session
        .call(name, &args)
        .expect_err("the call should be refused")
}

fn open(session: &Arc<Session>, path: &Path) -> u64 {
    ask(session, "project_open", json!({ "path": path }))["id"]
        .as_u64()
        .unwrap()
}

fn choose_presets(session: &Arc<Session>, project: u64) -> Value {
    let presets = ask(
        session,
        "presets",
        json!({ "vendor": "Snapmaker", "machine": MACHINE }),
    );
    ask(
        session,
        "project_set",
        json!({
            "project": project, "source": "presets", "vendor": "Snapmaker",
            "machine": MACHINE, "process": presets["processes"][0],
            "filaments": [presets["filaments"][0]], "initial": true,
        }),
    );
    presets
}

fn filaments(session: &Arc<Session>, project: u64, args: Value) -> Value {
    let mut args = args;
    args["project"] = json!(project);
    ask(session, "filament_edit", args)
}

fn detail(session: &Arc<Session>, project: u64) -> Value {
    ask(session, "project", json!({ "project": project }))
}

fn sliced(session: &Arc<Session>, project: u64, plate: Option<u64>) {
    ask(
        session,
        "slice",
        json!({ "project": project, "plate": plate }),
    );
    loop {
        let status = ask(session, "status", json!({ "project": project }));
        if status["state"] != "slicing" {
            assert_eq!(status["state"], "done", "{status}");
            return;
        }
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
}

/// The G-code of the plate shown, without the line naming its time.
fn gcode(session: &Arc<Session>, project: u64, dir: &Path) -> String {
    let path = dir.join("out.gcode");
    ask(
        session,
        "export",
        json!({ "project": project, "path": path.to_string_lossy() }),
    );
    std::fs::read_to_string(path)
        .unwrap()
        .lines()
        .filter(|line| !line.starts_with("; generated by "))
        .collect::<Vec<_>>()
        .join("\n")
}

/// The value a G-code file lists for a setting.
fn listed<'a>(gcode: &'a str, key: &str) -> Option<&'a str> {
    let prefix = format!("; {key} = ");
    gcode
        .lines()
        .find_map(|line| line.strip_prefix(prefix.as_str()))
}

fn texts(value: &Value) -> Vec<String> {
    value
        .as_array()
        .unwrap_or_else(|| panic!("{value} is not a list"))
        .iter()
        .map(|item| item.as_str().unwrap().to_owned())
        .collect()
}

#[test]
fn a_filament_added_to_a_one_filament_model_prints_what_is_given_it_with_a_tool_change() {
    let session = Arc::new(Session::new(None));
    let dir = tempfile::tempdir().unwrap();
    let id = open(&session, &reference(BARE));
    let presets = choose_presets(&session, id);
    let first = presets["filaments"][0].as_str().unwrap().to_owned();
    assert_eq!(detail(&session, id)["filament_count"], 1);
    sliced(&session, id, None);
    let before = gcode(&session, id, dir.path());
    assert_eq!(
        listed(&before, "filament_settings_id").map(|ids| ids.split(';').count()),
        Some(1)
    );

    let added = filaments(&session, id, json!({ "op": "add" }));
    assert_eq!(added["done"], "Add one filament");
    let project = &added["project"];
    assert_eq!(project["filament_count"], 2);
    // The reference's palette, from its first colour.
    assert_eq!(texts(&project["colours"])[1], "#00C1AE");
    // The last one's preset.
    assert_eq!(
        texts(&project["choices"]["filaments"]),
        [first.clone(), first.clone()]
    );
    assert_eq!(project["dirty"], true);
    assert_eq!(project["sliced"], false);
    assert_eq!(project["edit"]["undo"], "Add one filament");

    // A copy of the object, in filament 2.
    let scene = &added["scene"];
    let copy = scene["placings"][0]["id"].as_u64().unwrap();
    let cloned = ask(
        &session,
        "scene_edit",
        json!({ "project": id, "op": "clone", "copies": [copy] }),
    );
    let object = cloned["scene"]["objects"][1]["id"].as_u64().unwrap();
    ask(
        &session,
        "scene_edit",
        json!({ "project": id, "op": "filament", "object": object, "filament": 2 }),
    );
    sliced(&session, id, None);
    let two = gcode(&session, id, dir.path());
    assert_eq!(
        listed(&two, "filament_settings_id"),
        Some(format!("\"{first}\";\"{first}\"").as_str())
    );
    assert!(listed(&two, "filament_colour").unwrap().contains("#00C1AE"));
    // Filament 2 is printed by the second tool, and the tower is there.
    assert!(
        two.lines().any(|line| line.trim() == "T1"),
        "no tool change"
    );
    assert!(two.contains("Prime tower"), "no prime tower");
    // What is flushed between them is the size of the list.
    let matrix = listed(&two, "flush_volumes_matrix").unwrap();
    assert_eq!(matrix.split(',').count(), 4, "{matrix}");

    // Each of the three a step; taken back, the project slices as before.
    for _ in 0..3 {
        ask(&session, "undo", json!({ "project": id }));
    }
    let back = detail(&session, id);
    assert_eq!(back["filament_count"], 1);
    assert_eq!(
        texts(&back["choices"]["filaments"]),
        std::slice::from_ref(&first)
    );
    sliced(&session, id, None);
    assert_eq!(gcode(&session, id, dir.path()), before);
    // And made again.
    ask(&session, "redo", json!({ "project": id }));
    let again = detail(&session, id);
    assert_eq!(again["filament_count"], 2);
    assert_eq!(texts(&again["colours"])[1], "#00C1AE");
}

#[test]
fn removing_and_deleting_renumber_what_printed_in_the_filaments_after() {
    let session = Arc::new(Session::new(None));
    let dir = tempfile::tempdir().unwrap();
    let copy = dir.path().join("mcbrim_test.3mf");
    std::fs::copy(reference(THREE_PLATES), &copy).unwrap();
    let id = open(&session, &copy);
    let opened = detail(&session, id);
    assert_eq!(opened["filament_count"], 7);
    let colours = texts(&opened["colours"]);
    let names = texts(&opened["saved"]["filaments"]);
    let plates: Vec<Value> = opened["plates"].as_array().unwrap().clone();

    // The last cannot be taken when it is the only one; filament 0 is none.
    assert!(
        refused(
            &session,
            "filament_edit",
            json!({ "project": id, "op": "delete", "filament": 0 })
        )
        .contains("no filament 0")
    );

    let deleted = filaments(&session, id, json!({ "op": "delete", "filament": 3 }));
    assert_eq!(deleted["done"], "Delete this filament");
    let project = &deleted["project"];
    assert_eq!(project["filament_count"], 6);
    let mut expected = colours.clone();
    expected.remove(2);
    assert_eq!(texts(&project["colours"]), expected);
    let mut expected = names.clone();
    expected.remove(2);
    assert_eq!(texts(&project["saved"]["filaments"]), expected);
    // Every plate's filaments: 3 gone (its parts print in their object's,
    // filament 1), 4 to 7 one less.
    for (now, was) in project["plates"].as_array().unwrap().iter().zip(&plates) {
        let renumbered: Vec<u64> = {
            let mut list: Vec<u64> = was["filaments"]
                .as_array()
                .unwrap()
                .iter()
                .map(|filament| filament.as_u64().unwrap())
                .map(|filament| match filament {
                    3 => 1,
                    f if f > 3 => f - 1,
                    f => f,
                })
                .collect();
            list.sort_unstable();
            list.dedup();
            list
        };
        let shown: Vec<u64> = now["filaments"]
            .as_array()
            .unwrap()
            .iter()
            .map(|filament| filament.as_u64().unwrap())
            .collect();
        assert_eq!(shown, renumbered, "plate {}", now["id"]);
    }

    let removed = filaments(&session, id, json!({ "op": "remove_last" }));
    assert_eq!(removed["project"]["filament_count"], 5);

    // Saved and opened again in another session: as left.
    ask(&session, "project_save", json!({ "project": id }));
    let other = Arc::new(Session::new(None));
    let again = open(&other, &copy);
    let reopened = detail(&other, again);
    assert_eq!(reopened["filament_count"], 5);
    assert_eq!(
        texts(&reopened["colours"]),
        texts(&removed["project"]["colours"])
    );
    assert_eq!(
        reopened["plates"],
        removed["project"]["plates"]
            .clone()
            .as_array()
            .map(|plates| {
                Value::Array(
                    plates
                        .iter()
                        .map(|plate| {
                            let mut plate = plate.clone();
                            plate["sliced"] = json!(false);
                            plate
                        })
                        .collect(),
                )
            })
            .unwrap()
    );
    // And sliced as it was in the first session.
    sliced(&session, id, Some(1));
    sliced(&other, again, Some(1));
    assert_eq!(
        gcode(&session, id, dir.path()),
        gcode(&other, again, dir.path())
    );

    // Both taken back: the file's seven, as opened.
    ask(&session, "undo", json!({ "project": id }));
    ask(&session, "undo", json!({ "project": id }));
    let back = detail(&session, id);
    assert_eq!(back["filament_count"], 7);
    assert_eq!(texts(&back["colours"]), colours);
    assert_eq!(back["plates"].as_array().unwrap().len(), plates.len());
    for (now, was) in back["plates"].as_array().unwrap().iter().zip(&plates) {
        assert_eq!(now["filaments"], was["filaments"]);
    }
}

#[test]
fn a_filament_merged_into_another_prints_in_it() {
    let session = Arc::new(Session::new(None));
    let id = open(&session, &reference(THREE_PLATES));
    let opened = detail(&session, id);
    let plate1: Vec<u64> = opened["plates"][0]["filaments"]
        .as_array()
        .unwrap()
        .iter()
        .map(|filament| filament.as_u64().unwrap())
        .collect();
    assert!(plate1.contains(&3), "{plate1:?}");
    let merged = filaments(
        &session,
        id,
        json!({ "op": "merge", "filament": 3, "into": 5 }),
    );
    assert_eq!(merged["done"], "Merge with");
    let shown: Vec<u64> = merged["project"]["plates"][0]["filaments"]
        .as_array()
        .unwrap()
        .iter()
        .map(|filament| filament.as_u64().unwrap())
        .collect();
    // 3 into 5, which is 4 now; 4 to 7 one less.
    let mut expected: Vec<u64> = plate1
        .iter()
        .map(|filament| match *filament {
            3 => 4,
            f if f > 3 => f - 1,
            f => f,
        })
        .collect();
    expected.sort_unstable();
    expected.dedup();
    assert_eq!(shown, expected);
    assert!(
        refused(
            &session,
            "filament_edit",
            json!({ "project": id, "op": "merge", "filament": 2, "into": 2 })
        )
        .contains("cannot be merged")
    );
}

#[test]
fn a_colour_and_apply_all_are_steps_and_are_saved() {
    let session = Arc::new(Session::new(None));
    let dir = tempfile::tempdir().unwrap();
    let id = open(&session, &reference(BARE));
    let presets = choose_presets(&session, id);
    filaments(&session, id, json!({ "op": "add" }));
    let coloured = filaments(
        &session,
        id,
        json!({ "op": "colour", "filament": 2, "colour": "#000000" }),
    );
    assert_eq!(texts(&coloured["project"]["colours"])[1], "#000000");
    assert!(
        refused(
            &session,
            "filament_edit",
            json!({ "project": id, "op": "colour", "filament": 2, "colour": "black" })
        )
        .contains("not a colour")
    );

    // Every filament on another preset, and back with undo.
    let other = presets["filaments"]
        .as_array()
        .unwrap()
        .iter()
        .find(|name| name.as_str() != presets["filaments"][0].as_str())
        .unwrap()
        .as_str()
        .unwrap()
        .to_owned();
    let all = filaments(&session, id, json!({ "op": "apply_all", "preset": other }));
    assert_eq!(all["done"], "Apply All");
    assert_eq!(
        texts(&all["project"]["choices"]["filaments"]),
        [other.clone(), other.clone()]
    );
    ask(&session, "undo", json!({ "project": id }));
    let back = detail(&session, id);
    assert_ne!(texts(&back["choices"]["filaments"])[0], other);
    ask(&session, "redo", json!({ "project": id }));

    // Saved as a project, opened again: two filaments, their colours, the
    // presets.
    let path = dir.path().join("two.3mf");
    let saved = ask(
        &session,
        "project_save",
        json!({ "project": id, "path": path }),
    );
    assert_eq!(saved["saved"], true, "{saved}");
    let again = Arc::new(Session::new(None));
    let reopened = open(&again, &path);
    let shown = detail(&again, reopened);
    assert_eq!(shown["filament_count"], 2);
    assert_eq!(texts(&shown["colours"])[1], "#000000");
    assert_eq!(texts(&shown["saved"]["filaments"]), [other.clone(), other]);
}

#[test]
fn the_flushing_volumes_dialog_reads_recalculates_and_sets_in_one_step() {
    let session = Arc::new(Session::new(None));
    let dir = tempfile::tempdir().unwrap();
    let id = open(&session, &reference(BARE));
    choose_presets(&session, id);
    filaments(&session, id, json!({ "op": "add", "colour": "#000000" }));
    let shown = ask(&session, "flush_volumes", json!({ "project": id }));
    assert_eq!(shown["count"], 2);
    assert_eq!(texts(&shown["colours"]).len(), 2);
    let matrix: Vec<f64> = shown["matrix"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_f64().unwrap())
        .collect();
    assert_eq!(matrix.len(), 4);
    assert_eq!((matrix[0], matrix[3]), (0.0, 0.0));
    assert!(matrix[1] > 0.0 && matrix[2] > 0.0);
    // The multiplier a slice reads: the reference's default, here.
    let multiplier = shown["multiplier"].as_f64().unwrap();
    assert!(multiplier > 0.0 && multiplier <= 3.0);
    assert_eq!(shown["max_multiplier"], 3.0);
    assert_eq!(shown["typical_max"], 800);
    // Re-calculate answers the volumes for the colours given, changing
    // nothing.
    let calc = ask(
        &session,
        "flush_calc",
        json!({ "project": id, "colours": ["#F2754E", "#000000"] }),
    );
    assert_eq!(calc["matrix"], shown["matrix"]);
    let white = ask(
        &session,
        "flush_calc",
        json!({ "project": id, "colours": ["#000000", "#FFFFFF"] }),
    );
    assert!(white["matrix"][1].as_f64().unwrap() > white["matrix"][2].as_f64().unwrap());
    assert_eq!(
        ask(&session, "flush_volumes", json!({ "project": id }))["matrix"],
        shown["matrix"]
    );

    // OK: one pair doubled, the multiplier at 0.5; one step, undone and
    // done again.
    let doubled = [0.0, matrix[1] * 2.0, matrix[2], 0.0];
    let set = filaments(
        &session,
        id,
        json!({ "op": "flush", "matrix": doubled, "multiplier": 0.5 }),
    );
    assert_eq!(set["done"], "Flushing volumes");
    let now = ask(&session, "flush_volumes", json!({ "project": id }));
    assert_eq!(now["matrix"], json!(doubled));
    assert_eq!(now["multiplier"], 0.5);
    // The same again changes nothing and is no step.
    let same = filaments(
        &session,
        id,
        json!({ "op": "flush", "matrix": doubled, "multiplier": 0.5 }),
    );
    assert_eq!(same["done"], Value::Null);
    ask(&session, "undo", json!({ "project": id }));
    let back = ask(&session, "flush_volumes", json!({ "project": id }));
    assert_eq!(back["matrix"], shown["matrix"]);
    assert_eq!(back["multiplier"], shown["multiplier"]);
    ask(&session, "redo", json!({ "project": id }));
    // What is out of bounds is refused.
    for (matrix, multiplier) in [
        (json!([0.0, 1.0, 2.0]), 1.0),
        (json!([0.0, -5.0, 2.0, 0.0]), 1.0),
        (json!(doubled), 3.5),
    ] {
        refused(
            &session,
            "filament_edit",
            json!({ "project": id, "op": "flush", "matrix": matrix, "multiplier": multiplier }),
        );
    }
    // A slice, the file's settings and a save carry them.
    sliced(&session, id, None);
    let text = gcode(&session, id, dir.path());
    assert_eq!(listed(&text, "flush_multiplier"), Some("0.5"));
    let listed_matrix = listed(&text, "flush_volumes_matrix").unwrap();
    assert!(
        listed_matrix.contains(&format!("{}", matrix[1] * 2.0)),
        "{listed_matrix}"
    );
    let path = dir.path().join("flushed.3mf");
    ask(
        &session,
        "project_save",
        json!({ "project": id, "path": path }),
    );
    let again = Arc::new(Session::new(None));
    let reopened = open(&again, &path);
    let kept = ask(&again, "flush_volumes", json!({ "project": reopened }));
    assert_eq!(kept["matrix"], json!(doubled));
    assert_eq!(kept["multiplier"], 0.5);
}
