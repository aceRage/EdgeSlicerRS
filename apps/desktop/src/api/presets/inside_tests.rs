//! Presets kept inside a project ("Preset Inside Project") and "Detach
//! from parent".

use std::{io::Read, path::Path};

use super::*;

fn reference(path: &str) -> String {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../reference/EdgeSlicer")
        .join(path)
        .to_string_lossy()
        .into_owned()
}

fn new_session(dir: &Path) -> Arc<Session> {
    let session = Arc::new(Session::with_settings(None, Some(dir.to_owned())));
    ask(
        &session,
        "set_profiles",
        json!({ "dir": reference("resources/profiles") }),
    );
    ask(
        &session,
        "printers_save",
        json!({ "models": [{ "vendor": "Snapmaker", "model": "Snapmaker U1" }] }),
    );
    session
}

fn ask(session: &Arc<Session>, name: &str, args: Value) -> Value {
    session
        .call(name, &args)
        .unwrap_or_else(|error| panic!("{name}: {error}"))
}

/// A project with the reference's tolerance test on the U1.
fn project(session: &Arc<Session>, path: Option<&Path>) -> u64 {
    let path = path.map_or_else(
        || reference("resources/handy_models/OrcaToleranceTest.stl"),
        |path| path.to_string_lossy().into_owned(),
    );
    let id = ask(session, "project_open", json!({ "path": path }))["id"]
        .as_u64()
        .unwrap();
    ask(
        session,
        "printer_select",
        json!({ "project": id, "initial": true }),
    );
    id
}

/// The project's process with wall_loops set over it, saved inside it.
fn save_inside(session: &Arc<Session>, id: u64, name: &str, walls: u32) -> Value {
    ask(
        session,
        "process_set",
        json!({ "project": id, "key": "wall_loops", "value": walls }),
    );
    ask(
        session,
        "preset_save",
        json!({ "project": id, "kind": "process", "name": name, "inside": true }),
    )
}

fn sliced(session: &Arc<Session>, id: u64, out: &Path) -> String {
    ask(session, "slice", json!({ "project": id }));
    loop {
        let status = ask(session, "status", json!({ "project": id }));
        if status["state"] != "slicing" {
            assert_eq!(status["state"], "done", "{status}");
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
    ask(
        session,
        "export",
        json!({ "project": id, "path": out.to_string_lossy() }),
    );
    std::fs::read_to_string(out).unwrap()
}

/// The G-code without what names the presets or the time it was made.
fn moves(gcode: &str) -> Vec<&str> {
    gcode
        .lines()
        .filter(|line| {
            !line.contains("_settings_id")
                && !line.starts_with("; inherits")
                // The printers the process preset suits: a name, as the
                // reference's `full_fff_config` takes it from the preset.
                && !line.starts_with("; print_compatible_printers")
                && !line.contains("generated by")
                && !line.contains("different_settings_to_system")
        })
        .collect()
}

fn entry(zip: &Path, name: &str) -> Option<String> {
    let mut archive = zip::ZipArchive::new(std::fs::File::open(zip).unwrap()).unwrap();
    let mut file = archive.by_name(name).ok()?;
    let mut text = String::new();
    file.read_to_string(&mut text).unwrap();
    Some(text)
}

#[test]
fn a_process_saved_inside_the_project_is_listed_for_it_alone_and_not_written_to_disk() {
    let dir = tempfile::tempdir().unwrap();
    let session = new_session(dir.path());
    let id = project(&session, None);
    let system = ask(&session, "project", json!({ "project": id }))["choices"]["process"]
        .as_str()
        .unwrap()
        .to_owned();
    let saved = save_inside(&session, id, "Project process", 5);
    assert_eq!(saved["choices"]["process"], "Project process");
    assert_eq!(saved["choices"]["over"], json!({}));
    assert_eq!(
        saved["choices"]["inside"],
        json!([{ "kind": "process", "name": "Project process", "inherits": system }])
    );
    // Nothing in the person's presets.
    assert!(
        !dir.path()
            .join("user/default/process/Project process.json")
            .exists()
    );
    assert_eq!(
        ask(&session, "user_presets", json!({}))["process"],
        json!([])
    );
    // Listed under its own group for this project, after slicing with it.
    let lists = ask(
        &session,
        "presets",
        json!({ "project": id, "vendor": "Snapmaker", "machine": "Snapmaker U1 (0.4 nozzle)" }),
    );
    assert_eq!(lists["inside_processes"], json!(["Project process"]));
    let settled = ask(&session, "process", json!({ "project": id }));
    assert_eq!(settled["values"]["wall_loops"], json!("5"));
    // Another project does not have it.
    let other = ask(&session, "project_new", json!({}))["id"]
        .as_u64()
        .unwrap();
    let lists = ask(
        &session,
        "presets",
        json!({ "project": other, "vendor": "Snapmaker", "machine": "Snapmaker U1 (0.4 nozzle)" }),
    );
    assert_eq!(lists["inside_processes"], json!([]));

    // The dialog: where the preset saved from is, and a name taken
    // inside the project is saved over after the question.
    let check = ask(
        &session,
        "preset_check",
        json!({ "project": id, "kind": "process", "name": "Project process" }),
    );
    assert_eq!(check["from"], "inside");
    assert_eq!(check["existing"], "inside");
    assert_eq!(check["parent"], json!(system));
    let check = ask(
        &session,
        "preset_check",
        json!({ "project": id, "kind": "process", "name": "Elsewhere" }),
    );
    assert_eq!(check["existing"], Value::Null);
    assert_eq!(check["level"], "ok");
}

#[test]
fn two_open_projects_with_a_same_named_preset_inside_do_not_mix() {
    let dir = tempfile::tempdir().unwrap();
    let session = new_session(dir.path());
    let first = project(&session, None);
    let copy = dir.path().join("copy.stl");
    std::fs::copy(
        reference("resources/handy_models/OrcaToleranceTest.stl"),
        &copy,
    )
    .unwrap();
    let second = project(&session, Some(&copy));
    assert_ne!(first, second);
    save_inside(&session, first, "Walls", 5);
    save_inside(&session, second, "Walls", 2);
    let walls = |id: u64| {
        ask(&session, "process", json!({ "project": id }))["values"]["wall_loops"].clone()
    };
    assert_eq!(walls(first), json!("5"));
    assert_eq!(walls(second), json!("2"));
    // Deleted from one, the other keeps its own.
    let asked = ask(
        &session,
        "preset_delete",
        json!({ "project": first, "kind": "process", "preset": "Walls" }),
    );
    assert_eq!(asked["deleted"], false);
    assert_eq!(
        asked["ask"],
        "Are you sure you want to Delete the selected preset?"
    );
    let gone = ask(
        &session,
        "preset_delete",
        json!({ "project": first, "kind": "process", "preset": "Walls", "confirm": true }),
    );
    assert_eq!(gone["choices"]["inside"], json!([]));
    assert_ne!(gone["choices"]["process"], "Walls");
    assert_eq!(walls(second), json!("2"));
}

#[test]
fn a_preset_inside_is_saved_with_the_project_opened_again_and_slices_the_same() {
    let dir = tempfile::tempdir().unwrap();
    let session = new_session(dir.path());
    let id = project(&session, None);
    save_inside(&session, id, "Project process", 5);
    // The filament too, "Use for every printer".
    ask(
        &session,
        "settings_set",
        json!({ "project": id, "kind": "filament", "filament": 1, "key": "nozzle_temperature", "value": 231 }),
    );
    ask(
        &session,
        "preset_save",
        json!({ "project": id, "kind": "filament", "filament": 1, "name": "Project PLA", "inside": true, "every_printer": true }),
    );
    let before = sliced(&session, id, &dir.path().join("before.gcode"));
    let path = dir.path().join("inside.3mf");
    let saved = ask(
        &session,
        "project_save",
        json!({ "project": id, "path": path.to_string_lossy() }),
    );
    assert_eq!(saved["saved"], true, "{saved}");
    // As the reference writes them: `from` "project", the parent named,
    // what differs and the names.
    let process = entry(&path, "Metadata/process_settings_1.config").unwrap();
    assert!(process.contains("\"from\": \"project\""), "{process}");
    assert!(process.contains("\"name\": \"Project process\""));
    assert!(process.contains("\"print_settings_id\": \"Project process\""));
    assert!(process.contains("\"wall_loops\": \"5\""));
    assert!(process.ends_with("}\n"));
    let filament = entry(&path, "Metadata/filament_settings_1.config").unwrap();
    assert!(
        filament.contains("\"compatible_printers\": []"),
        "{filament}"
    );
    assert!(filament.contains("\"231\""));
    let settings = entry(&path, "Metadata/project_settings.config").unwrap();
    assert!(settings.contains("\"print_settings_id\": \"Project process\""));

    // Opened in another session: the project's presets come with it, and
    // picked, it slices as before.
    let other_dir = tempfile::tempdir().unwrap();
    let other = new_session(other_dir.path());
    let opened = ask(
        &other,
        "project_open",
        json!({ "path": path.to_string_lossy() }),
    )["id"]
        .as_u64()
        .unwrap();
    let project = ask(&other, "project", json!({ "project": opened }));
    let names: Vec<&str> = project["choices"]["inside"]
        .as_array()
        .unwrap()
        .iter()
        .map(|preset| preset["name"].as_str().unwrap())
        .collect();
    assert_eq!(names, ["Project process", "Project PLA"]);
    ask(
        &other,
        "printer_select",
        json!({ "project": opened, "vendor": "Snapmaker", "model": "Snapmaker U1" }),
    );
    ask(
        &other,
        "project_set",
        json!({ "project": opened, "process": "Project process", "filaments": ["Project PLA"] }),
    );
    let after = sliced(&other, opened, &other_dir.path().join("after.gcode"));
    let (before_moves, after_moves) = (moves(&before), moves(&after));
    let differ: Vec<(&&str, &&str)> = before_moves
        .iter()
        .zip(&after_moves)
        .filter(|(a, b)| a != b)
        .take(10)
        .collect();
    assert!(
        differ.is_empty() && before_moves.len() == after_moves.len(),
        "{differ:?}"
    );
    // Saved again, the entries are written as they were read.
    let again = other_dir.path().join("again.3mf");
    ask(
        &other,
        "project_save",
        json!({ "project": opened, "path": again.to_string_lossy() }),
    );
    assert_eq!(
        entry(&again, "Metadata/process_settings_1.config").unwrap(),
        process
    );
    assert_eq!(
        entry(&again, "Metadata/filament_settings_1.config").unwrap(),
        filament
    );
}

#[test]
fn a_preset_detached_from_its_parent_needs_none_and_slices_the_same() {
    let dir = tempfile::tempdir().unwrap();
    let session = new_session(dir.path());
    let id = project(&session, None);
    // Not offered until Preferences' "Develop mode" is on.
    let check = ask(
        &session,
        "preset_check",
        json!({ "project": id, "kind": "process" }),
    );
    assert_eq!(check["develop"], false);
    ask(
        &session,
        "preference_set",
        json!({ "key": "developer_mode", "value": "true" }),
    );
    let check = ask(
        &session,
        "preset_check",
        json!({ "project": id, "kind": "process" }),
    );
    assert_eq!(check["develop"], true);
    let system = check["parent"].as_str().unwrap().to_owned();
    let before = sliced(&session, id, &dir.path().join("before.gcode"));
    ask(
        &session,
        "preset_save",
        json!({ "project": id, "kind": "process", "name": "Alone", "detach": true }),
    );
    // In base/, laid over nothing, every value written.
    let file = dir.path().join("user/default/process/base/Alone.json");
    let text = std::fs::read_to_string(&file).unwrap();
    assert!(text.contains("\"inherits\": \"\""), "{text}");
    let own = edge_config::Settings::from_json(&text).unwrap();
    let parent = ask(&session, "process", json!({ "project": id }))["values"].clone();
    // Every value the preset had, not only what differs from its parent:
    // the vendor's chain written out (the reference writes every option
    // of the kind; both fill the rest with the same defaults).
    assert!(own.len() > 100, "{} values", own.len());
    // Read back in a new session, it needs no parent.
    let users = edge_config::UserPresets::open(dir.path().join("user/default"));
    let alone = users.get(edge_config::Kind::Process, "Alone").unwrap();
    assert_eq!(alone.inherits, None);
    let resolved = users
        .resolve(edge_config::Kind::Process, "Alone", &|name| {
            panic!("{name} was looked for")
        })
        .unwrap();
    assert_eq!(resolved.text("wall_loops"), own.text("wall_loops"));
    assert!(parent.is_object());
    let after = sliced(&session, id, &dir.path().join("after.gcode"));
    let (before, after) = (moves(&before), moves(&after));
    let differ: Vec<(&&str, &&str)> = before
        .iter()
        .zip(&after)
        .filter(|(a, b)| a != b)
        .take(10)
        .collect();
    assert!(
        differ.is_empty() && before.len() == after.len(),
        "{differ:?}"
    );
    assert_ne!(system, "Alone");
}

#[test]
fn a_printer_saved_inside_the_project_is_listed_and_picked_and_keeps_its_presets() {
    let dir = tempfile::tempdir().unwrap();
    let session = new_session(dir.path());
    let id = project(&session, None);
    let before = ask(&session, "project", json!({ "project": id }))["choices"].clone();
    ask(
        &session,
        "settings_set",
        json!({ "project": id, "kind": "printer", "key": "printable_height", "value": 250 }),
    );
    let saved = ask(
        &session,
        "preset_save",
        json!({ "project": id, "kind": "printer", "name": "Project U1", "inside": true }),
    );
    assert_eq!(saved["choices"]["machine"], "Project U1");
    // The process and filaments still fit: it stands in for its parent.
    assert_eq!(saved["choices"]["process"], before["process"]);
    assert_eq!(saved["choices"]["filaments"], before["filaments"]);
    let listing = ask(&session, "printers", json!({ "project": id }));
    assert_eq!(listing["inside"][0]["name"], "Project U1");
    assert_eq!(listing["inside"][0]["base"], "Snapmaker U1 (0.4 nozzle)");
    assert_eq!(listing["selected"]["inside"], true);
    let lists = ask(
        &session,
        "presets",
        json!({ "project": id, "vendor": "Snapmaker", "machine": "Project U1" }),
    );
    assert!(lists["processes"].as_array().unwrap().len() > 3, "{lists}");
    // Not remembered with the printers: no other project has it.
    let other = ask(&session, "project_new", json!({}))["id"]
        .as_u64()
        .unwrap();
    let picked = ask(
        &session,
        "printer_select",
        json!({ "project": other, "initial": true }),
    );
    assert_ne!(picked["choices"]["machine"], "Project U1");
    let refused = session
        .call(
            "printer_select",
            &json!({ "project": other, "vendor": "Snapmaker", "machine": "Project U1" }),
        )
        .unwrap_err();
    assert!(
        refused.contains("not a printer preset of your own"),
        "{refused}"
    );
    // Back on it in its own project.
    ask(
        &session,
        "printer_select",
        json!({ "project": id, "vendor": "Snapmaker", "model": "Snapmaker U1" }),
    );
    let back = ask(
        &session,
        "printer_select",
        json!({ "project": id, "vendor": "Snapmaker", "machine": "Project U1" }),
    );
    assert_eq!(back["choices"]["machine"], "Project U1");
}
