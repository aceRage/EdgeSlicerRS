#!/usr/bin/env python3
"""Writes crates/edge-config/src/reference_defaults.txt: every setting the
reference slicer knows, with its default, as the reference itself writes
them into a G-code file's settings block.

    tools/make_defaults.py /path/to/EdgeSlicer.app/Contents/MacOS/EdgeSlicer

The reference is given a cube with a project that sets nothing, so what it
writes back is its defaults. It will not slice with relative extrusion and
no layer-change G-code, so that one setting is turned off for the run and
put back to its default (on) in the table. Some settings it lists only
when a profile gives them (the printer's variant, the filament's vendor):
those are learnt from a project in the reference's own tests and listed
with a leading `?`, as known but without a default. Run this again
whenever the `reference/EdgeSlicer` pin is moved.
"""
import json, os, re, subprocess, sys, tempfile, zipfile

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "crates", "edge-config", "src", "reference_defaults.txt")
reference = sys.argv[1]

def sliced_by_reference(work, project, name):
    """The G-code the reference writes for a project."""
    sliced = os.path.join(work, name)
    # Its own empty data directory, and no hub: it must not touch the user's.
    subprocess.run(
        [reference, "--datadir", os.path.join(work, "data"), "--no-hub", "--no-thumbnails",
         "--slice", "1", "--outputdir", sliced, project],
        cwd=work, check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return open(os.path.join(sliced, "plate_1.gcode"), encoding="utf-8").read()

with tempfile.TemporaryDirectory() as work:
    source = os.path.join(work, "bare.3mf")
    with zipfile.ZipFile(source, "w") as z:
        z.writestr("Metadata/project_settings.config", json.dumps({"use_relative_e_distances": "0"}))
    project = os.path.join(work, "cube.3mf")
    subprocess.run([sys.executable, os.path.join(here, "make_fixture.py"), project, source, "cube"], check=True)
    text = sliced_by_reference(work, project, "bare")
    real = os.path.join(here, "..", "reference", "EdgeSlicer", "tests", "data", "support_corpus", "twopart_groups.3mf")
    profiled = sliced_by_reference(work, os.path.abspath(real), "profiled")

producer = re.search(r"^; generated by (.*?) on ", text, re.M).group(1)
block = text.split("; CONFIG_BLOCK_START\n", 1)[1].split("; CONFIG_BLOCK_END", 1)[0]
# The last four lines repeat settings under older names; they are not settings.
extra = {"first_layer_bed_temperature", "bed_shape", "first_layer_temperature", "first_layer_height"}
# The reference writes the prime tower's place twice, once to three
# decimals; the later, plain one is the setting.
found = {}
for line in block.splitlines():
    key, _, value = line[2:].partition(" =")
    value = value[1:] if value.startswith(" ") else value
    if key in extra:
        continue
    if key == "use_relative_e_distances":
        value = "1"
    found[key] = value
lines = [f"{key} = {value}" if value else f"{key} =" for key, value in found.items()]
listed = profiled.split("; CONFIG_BLOCK_START\n", 1)[1].split("; CONFIG_BLOCK_END", 1)[0]
only_profiled = sorted({line[2:].partition(" =")[0] for line in listed.splitlines()} - set(found) - extra)
lines += [f"?{key}" for key in only_profiled]

with open(out, "w", encoding="utf-8") as f:
    f.write(f"# The reference's defaults, as {producer} writes them. Made by tools/make_defaults.py; do not edit.\n")
    f.write(f"# producer: {producer.split(' (')[0]}\n")
    f.write("\n".join(lines) + "\n")
print(f"{len(found)} defaults and {len(only_profiled)} more names written to {os.path.normpath(out)}")
