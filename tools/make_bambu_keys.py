#!/usr/bin/env python3
"""Writes crates/edge-config/src/bambu/known.rs: what "Export Bambu 3MF"
translates a project's settings with, read from the pinned reference.

- every option Bambu Studio keeps when it loads a project, with its type,
  whether it may hold "nil", its per-extruder-variant class and the enum
  values it accepts, and the enum values of ours it spells otherwise
  (src/libslic3r/Format/BambuKnownKeys.cpp, which the reference generates
  from Bambu Studio's PrintConfig.cpp with scripts/gen_bambu_known_keys.py);
- the settings both have under other names, and the enum values the two
  spell differently (Format/BambuKeyAliases.cpp `make_aliases`,
  `make_enum_aliases`), each value conversion named by the reference's
  function, which edge-config's `bambu` module carries out;
- what a percentage of each of our options is of (`def->ratio_over` in
  src/libslic3r/PrintConfig.cpp), and the filament options kept per flow
  variant (`filament_flow_variant_options`).

    tools/make_bambu_keys.py [--check]

Nothing is run. Run it again whenever the pin is moved; `--check` writes
nothing and fails when the file is not what would be written.
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..")
reference = os.path.join(root, "reference", "EdgeSlicer", "src", "libslic3r")
out = os.path.join(root, "crates", "edge-config", "src", "bambu", "known.rs")


def read(*path):
    with open(os.path.join(reference, *path), encoding="utf-8") as f:
        return f.read()


def body(source, start):
    """The text from `start` to the end of the brace block that opens after it."""
    at = source.index(start)
    at = source.index("{", at)
    depth = 0
    for i in range(at, len(source)):
        if source[i] == "{":
            depth += 1
        elif source[i] == "}":
            depth -= 1
            if depth == 0:
                return source[at:i + 1]
    raise SystemExit(f"no end to {start}")


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


STRING = r'"((?:[^"\\]|\\.)*)"'
NULLABLE_STRING = r'(?:"((?:[^"\\]|\\.)*)"|nullptr)'


def rust(text):
    """A Rust string literal of C++ literal text (its escapes kept)."""
    return '"' + (text or "") + '"'


def option(text):
    return "None" if text is None else f"Some({rust(text)})"


def main():
    check = "--check" in sys.argv[1:]
    known = read("Format", "BambuKnownKeys.cpp")
    version = re.search(r'bambu_reference_version\(\) \{ return "([^"]+)"', known).group(1)
    commit = re.search(r'bambu_reference_commit\(\) \{ return "([^"]+)"', known).group(1)
    defs_text = strip_comments(body(known, "bambu_key_defs()"))
    defs = [m.groups() for m in re.finditer(
        r'\{ ' + STRING + r', ' + STRING + r', (true|false), VariantClass::(\w+), ' + NULLABLE_STRING + r' \}',
        defs_text)]
    if len(defs) < 500:
        raise SystemExit(f"only {len(defs)} Bambu keys read")
    translations = re.findall(r'\{ ' + STRING + ', ' + STRING + ', ' + STRING + r' \}',
                              strip_comments(body(known, "generated_enum_translations()")))

    aliases_source = read("Format", "BambuKeyAliases.cpp")
    alias_rows = re.findall(
        r'\{ ' + STRING + r',\s+' + STRING + r',\s+(\w+), (\w+),\s*' + NULLABLE_STRING + r'\s*\}',
        strip_comments(body(aliases_source, "std::vector<Alias> make_aliases()")))
    enum_body = strip_comments(body(aliases_source, "std::vector<EnumAlias> make_enum_aliases()"))
    enum_rows = re.findall(r'\{ ' + STRING + r',\s*' + STRING + r',\s*' + STRING + r',\s*(true|false) \}', enum_body)
    loop = re.search(r'for \(const char \*key : \{([^}]*)\}\)\s*v\.push_back\(\{ key, ' + STRING + ', ' + STRING
                     + r', (true|false) \}\);', enum_body)
    if loop:
        for key in re.findall(STRING, loop.group(1)):
            enum_rows.append((key, loop.group(2), loop.group(3), loop.group(4)))

    config = read("PrintConfig.cpp")
    ratio = {}
    current = None
    for line in config.splitlines():
        found = re.search(r'def\s*=\s*this->add(?:_nullable)?\("([^"]+)"', line)
        if found:
            current = found.group(1)
            continue
        if re.search(r'def\s*=\s*this->add', line):
            current = None
        over = re.search(r'def->ratio_over = "([^"]*)"', line)
        if over and current:
            ratio[current] = over.group(1)
    flow = re.findall(STRING, strip_comments(body(config, "filament_flow_variant_options()")))

    lines = [
        "// GENERATED by tools/make_bambu_keys.py from the pinned reference; do not edit.",
        f"// Bambu Studio {version} (commit {commit}), as Format/BambuKnownKeys.cpp has it.",
        "",
        "use super::{Def, Variant};",
        "",
        f'pub(super) const REFERENCE_VERSION: &str = "{version}";',
        "",
        "/// Every option Bambu Studio keeps when it loads a project (`bambu_key_defs`).",
        "pub(super) const KEYS: &[Def] = &[",
    ]
    for key, kind, nullable, variant, enums in defs:
        lines.append(f"    Def {{ key: {rust(key)}, kind: {rust(kind)}, nullable: {nullable}, "
                     f"variant: Variant::{variant}, enums: {option(enums)} }},")
    lines += [
        "];",
        "",
        "/// Our enum values Bambu does not take as written: key, ours, Bambu's (\"\": none)",
        "/// (`generated_enum_translations`).",
        "pub(super) const ENUMS: &[(&str, &str, &str)] = &[",
    ]
    lines += [f"    ({rust(k)}, {rust(o)}, {rust(b)})," for k, o, b in translations]
    lines += [
        "];",
        "",
        "/// Settings both have under other names: ours, Bambu's, the conversion to",
        "/// Bambu's value (the reference's function), why it can refuse one",
        "/// (`make_aliases`).",
        "pub(super) const ALIASES: &[(&str, &str, Option<&str>, Option<&str>)] = &[",
    ]
    for ours, bambu, to_bambu, _from, reason in alias_rows:
        fn = None if to_bambu == "nullptr" else to_bambu
        lines.append(f"    ({rust(ours)}, {rust(bambu)}, {option(fn)}, {option(reason if reason else None)}),")
    lines += [
        "];",
        "",
        "/// Enum values spelled otherwise for the same key: key, ours, Bambu's",
        "/// (`make_enum_aliases`).",
        "pub(super) const ENUM_ALIASES: &[(&str, &str, &str)] = &[",
    ]
    lines += [f"    ({rust(k)}, {rust(o)}, {rust(b)})," for k, o, b, _ in enum_rows]
    lines += [
        "];",
        "",
        "/// What a percentage of one of our options is of (`ratio_over`).",
        "pub(super) const RATIO_OVER: &[(&str, &str)] = &[",
    ]
    lines += [f"    ({rust(k)}, {rust(v)})," for k, v in sorted(ratio.items())]
    lines += [
        "];",
        "",
        "/// The filament options our full settings keep per flow variant",
        "/// (`filament_flow_variant_options`).",
        "pub(super) const FILAMENT_FLOW_VARIANT: &[&str] = &[",
    ]
    lines += [f"    {rust(k)}," for k in flow]
    lines += ["];", ""]
    text = "\n".join(lines)

    if check:
        try:
            with open(out, encoding="utf-8") as f:
                if f.read() == text:
                    print("up to date")
                    return
        except FileNotFoundError:
            pass
        raise SystemExit(f"{out} is not what tools/make_bambu_keys.py would write")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{len(defs)} Bambu keys, {len(translations)} enum translations, {len(alias_rows)} renamed keys, "
          f"{len(enum_rows)} enum spellings, {len(ratio)} ratios, {len(flow)} flow-variant options")


main()
